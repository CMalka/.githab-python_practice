import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df =pd.read_csv('/content/student_performance_dataset.csv')
df.info()
df.columns
df.head(5)

df["gender"].value_counts()

df['parental_education'] = df['parental_education'].fillna('Unknown')
df['parental_education'].value_counts()

colors = ['#D95FB0', '#615FD9']

df['gender'].value_counts().plot( kind='pie', autopct="%1.1f%%", colors=colors,)
df['parental_education'].value_counts().plot( kind='pie', autopct='%1.1f%%', title= 'parental_education', ylabel= ' ')

q1 = df.groupby(['final_grade','gender'],as_index = False).agg(num= ('student_id', 'count'))
sns.barplot(data=q1,
    x='final_grade',
    y='num',
    hue='gender'
)

plt.title('Number of Students by Final Grade and Gender')
plt.xlabel('Final Grade')
plt.ylabel('Number of Students')
plt.show()


sleep_hours_affect= df.groupby(['final_grade','sleep_hours'],as_index = False).agg(num= ('student_id', 'count'))
sleep_hours_affect
sns.histplot( data=sleep_hours_affect, x='sleep_hours', y='num', hue='final_grade')
plt.title('Number of Students by Final Grade and Sleep Hours')
plt.xlabel('Sleep Hours')
plt.ylabel('Number of Students')
plt.show()